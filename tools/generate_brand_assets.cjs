#!/usr/bin/env node
// Nexo ribbon: one geometry for adaptive, themed, in-app and notification icons.
// Run from any directory: node tools/generate_brand_assets.cjs
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const shapes = [
  { d: 'M65.4,39.6 L78,33 L78,68.4 L65.4,59 Z',
    from: [65, 34], to: [78, 69], colors: ['#A49AFF', '#5833D6'] },
  { d: 'M30,38.3 L44.5,43 L44.5,68.4 L30,75 Z',
    from: [33, 40], to: [44, 73], colors: ['#176CBA', '#687EFF'] },
  { d: 'M30,38.3 L37.6,34 Q40.3,32.5 42.4,34.9 L78,67.1 L78,68.4 L69.5,73.2 Q67.5,74.5 65.9,72.8 L39,48.6 L39,70.9 L30,75 Z',
    from: [31, 34], to: [77, 72], colors: ['#41F3EB', '#52AAFF', '#8B42F5'] },
];
const bg = { from: [0, 0], to: [108, 108], colors: ['#19243E', '#0B1023'] };
const gradient = ({ from, to, colors }) => `        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="${from[0]}" android:startY="${from[1]}" android:endX="${to[0]}" android:endY="${to[1]}">
${colors.map((color, i) => `                <item android:offset="${i / (colors.length - 1)}" android:color="${color}" />`).join('\n')}
            </gradient>
        </aapt:attr>`;
const coloredPath = shape => `    <path android:pathData="${shape.d}">\n${gradient(shape)}\n    </path>`;
const ribbon = shapes.map(coloredPath).join('\n');
const mono = shapes.map(s => `    <path android:fillColor="#FFFFFFFF" android:pathData="${s.d}" />`).join('\n');
function vector(body, size = 108, viewport = 108) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_brand_assets.cjs. Edit the source geometry there. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="${size}dp" android:height="${size}dp"
    android:viewportWidth="${viewport}" android:viewportHeight="${viewport}">
${body}
</vector>\n`;
}
const enlarge = body => `    <group android:pivotX="54" android:pivotY="54" android:scaleX="1.5" android:scaleY="1.5">\n${body}\n    </group>`;
const roundedSquare = 'M24,0 H84 Q108,0 108,24 V84 Q108,108 84,108 H24 Q0,108 0,84 V24 Q0,0 24,0 Z';
const outputs = {
  'app/src/main/res/drawable/ic_launcher_background.xml': vector(coloredPath({ d: 'M0,0 H108 V108 H0 Z', ...bg })),
  // Every point of the foreground lies inside the adaptive icon's 66dp safe circle.
  'app/src/main/res/drawable/ic_launcher_foreground.xml': vector(ribbon),
  'app/src/main/res/drawable/ic_launcher_monochrome.xml': vector(mono),
  'app/src/main/res/drawable/ic_nexo_logo.xml': vector(coloredPath({ d: roundedSquare, ...bg }) + '\n' + enlarge(ribbon)),
  'app/src/main/res/drawable/ic_nexo_emblem.xml': vector(`    <group android:translateX="-27" android:translateY="-27">\n${ribbon}\n    </group>`, 48, 54),
  'app/src/main/res/drawable/ic_stat_nexo.xml': vector(enlarge(mono), 24),
};
const svgGradient = (id, { from, to, colors }) => `<linearGradient id="${id}" gradientUnits="userSpaceOnUse" x1="${from[0]}" y1="${from[1]}" x2="${to[0]}" y2="${to[1]}">${colors.map((c, i) => `<stop offset="${i / (colors.length - 1)}" stop-color="${c}"/>`).join('')}</linearGradient>`;
outputs['docs/brand/nexo.svg'] = `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 108 108" role="img" aria-label="Nexo Browser">
<!-- Generated by tools/generate_brand_assets.cjs. -->
<defs>${svgGradient('bg', bg)}${shapes.map((s, i) => svgGradient('n' + i, s)).join('')}</defs>
<path d="${roundedSquare}" fill="url(#bg)"/>
<g transform="translate(54 54) scale(1.5) translate(-54 -54)">${shapes.map((s, i) => `<path d="${s.d}" fill="url(#n${i})"/>`).join('')}</g>
</svg>\n`;
for (const [name, content] of Object.entries(outputs)) {
  const dest = path.join(root, name);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, content);
}
console.log('Updated six Android vector drawables and the SVG brand preview.');
